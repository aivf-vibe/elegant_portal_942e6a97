// Mining dashboard simulation
function updateMiningStats() {
    const stats = document.querySelectorAll('.stat-item .value');
    if (stats.length > 0) {
        const newValues = [
            (120 + Math.random() * 10).toFixed(1) + ' TH/s',
            Math.floor(65 + Math.random() * 10) + '°C',
            (2.0 + Math.random() * 0.2).toFixed(1) + ' kW',
            '0.002' + Math.floor(Math.random() * 100).toString().padStart(2, '0')
        ];
        
        stats.forEach((stat, index) => {
            if (newValues[index]) {
                stat.textContent = newValues[index];
            }
        });
    }
}

// Update mining stats every 5 seconds
setInterval(updateMiningStats, 5000);

// Lazy loading for images
const imageObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const img = entry.target;
            img.src = img.dataset.src;
            img.classList.remove('lazy');
            imageObserver.unobserve(img);
        }
    });
});

document.querySelectorAll('img[data-src]').forEach(img => {
    imageObserver.observe(img);
});

